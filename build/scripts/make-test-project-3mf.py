#!/usr/bin/env python3
"""Erzeugt eine kleine PrusaSlicer-kompatible Mehrbett-3MF für Tests."""

from __future__ import annotations

import argparse
import pathlib
import zipfile


CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
 <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
 <Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>
</Types>
"""

RELATIONSHIPS = """<?xml version="1.0" encoding="UTF-8"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
 <Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>
</Relationships>
"""

# Bett 2 benutzt absichtlich PrusaSlicers Legacy-Abstand:
# Bettbreite 250 mm + 20 % = 300 mm. rearrange_after_load erkennt diesen
# alten Desktop-3MF-Aufbau und wandelt ihn in das aktuelle Raster um.
MODEL = """<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xml:lang="en-US"
 xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"
 xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">
 <metadata name="slic3rpe:Version3mf">1</metadata>
 <metadata name="Application">PrusaSlicer-2.9.6</metadata>
 <resources>
  <object id="1" type="model" name="PSMobile Test Cube">
   <mesh>
    <vertices>
     <vertex x="0" y="0" z="0"/><vertex x="20" y="0" z="0"/>
     <vertex x="20" y="20" z="0"/><vertex x="0" y="20" z="0"/>
     <vertex x="0" y="0" z="20"/><vertex x="20" y="0" z="20"/>
     <vertex x="20" y="20" z="20"/><vertex x="0" y="20" z="20"/>
    </vertices>
    <triangles>
     <triangle v1="3" v2="2" v3="1"/><triangle v1="1" v2="0" v3="3"/>
     <triangle v1="4" v2="5" v3="6"/><triangle v1="6" v2="7" v3="4"/>
     <triangle v1="0" v2="1" v3="5"/><triangle v1="5" v2="4" v3="0"/>
     <triangle v1="1" v2="2" v3="6"/><triangle v1="6" v2="5" v3="1"/>
     <triangle v1="2" v2="3" v3="7"/><triangle v1="7" v2="6" v3="2"/>
     <triangle v1="3" v2="0" v3="4"/><triangle v1="4" v2="7" v3="3"/>
    </triangles>
   </mesh>
  </object>
 </resources>
 <build>
  <item objectid="1" transform="1 0 0 0 1 0 0 0 1 115 95 0"/>
  <item objectid="1" transform="1 0 0 0 1 0 0 0 1 415 95 0"/>
 </build>
</model>
"""

PRINT_CONFIG = """; generated by PSMobile contract tests
; printer_technology = FFF
; printer_settings_id = PSMobile Test Printer 0.4
; print_settings_id = PSMobile Test Print
; filament_settings_id = PSMobile Test PLA
; printer_model = PSM_TEST
; printer_variant = 0.4
; bed_shape = 0x0,250x0,250x210,0x210
; max_print_height = 220
; nozzle_diameter = 0.4
; filament_diameter = 1.75
; post_process = must-not-run
"""

# Der Name muss exakt zu einem mitgelieferten FFF-Profil passen. Die
# Contract-Prüfung installiert vor dem Import nur COREONE/0.4 und kann
# damit unterscheiden, ob load_config_model ein lokales Profil erzeugt
# oder das bereits installierte Preset übernimmt.
INSTALLED_CORE_ONE_CONFIG = """; generated by PSMobile contract tests
; printer_technology = FFF
; printer_settings_id = Prusa CORE One 0.4 nozzle
; print_settings_id = 0.20mm SPEED @COREONE 0.4
; filament_settings_id = Prusament PLA @COREONE
; printer_model = COREONE
; printer_variant = 0.4
; bed_shape = 0x0,250x0,250x210,0x210
; max_print_height = 220
; nozzle_diameter = 0.4
; filament_diameter = 1.75
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--installed-core-one",
        action="store_true",
        help="embed an exact bundled CORE One 0.4 profile",
    )
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(
        args.output, "w", compression=zipfile.ZIP_DEFLATED
    ) as archive:
        archive.writestr("[Content_Types].xml", CONTENT_TYPES)
        archive.writestr("_rels/.rels", RELATIONSHIPS)
        archive.writestr("3D/3dmodel.model", MODEL)
        archive.writestr(
            "Metadata/Slic3r_PE.config",
            INSTALLED_CORE_ONE_CONFIG if args.installed_core_one else PRINT_CONFIG,
        )
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
